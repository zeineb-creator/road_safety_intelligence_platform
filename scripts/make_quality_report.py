import os
from datetime import date

import psycopg
from dotenv import load_dotenv

load_dotenv()
conn = psycopg.connect(
    host="localhost",
    port=int(os.environ.get("POSTGRES_PORT", "5432")),
    dbname=os.environ["POSTGRES_DB"],
    user=os.environ["POSTGRES_USER"],
    password=os.environ["POSTGRES_PASSWORD"],
)

REGION_SQL = "('75','92','93','94')"


def rows(sql):
    with conn.cursor() as cur:
        cur.execute(sql)
        return cur.fetchall()


def table(headers, data):
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(str(v) for v in r) + " |" for r in data]
    return "\n".join(lines)


out = [f"# Data quality report (generated {date.today()})", "",
       "Generated by `scripts/make_quality_report.py` from the database. "
       "Do not edit by hand: change the script and regenerate.", ""]

# ---- Source data (table `crashes`) ----------------------------------------
out += ["## Rows and exclusions per year", "", table(
    ["Year", "Rows", "Overseas", "Bad coordinates", "Bad datetime", "Usable"],
    rows("""SELECT year, count(*),
        count(*) FILTER (WHERE exclusion_reason='overseas'),
        count(*) FILTER (WHERE exclusion_reason='bad_coordinates'),
        count(*) FILTER (WHERE exclusion_reason='bad_datetime'),
        count(*) FILTER (WHERE exclusion_reason IS NULL)
        FROM crashes GROUP BY year ORDER BY year""")), ""]

out += ["## Excluded for bad coordinates", "", table(
    ["Accident", "Year", "Dep", "Commune", "lat", "lon"],
    rows("""SELECT accident_id, year, dep, com, lat, lon FROM crashes
        WHERE exclusion_reason='bad_coordinates' ORDER BY accident_id""")), ""]

out += ["## Usable accidents: people killed and hospitalized", "", table(
    ["Year", "Accidents", "Killed", "Hospitalized"],
    rows("""SELECT year, count(*), sum(n_killed), sum(n_hospitalized) FROM crashes
        WHERE exclusion_reason IS NULL GROUP BY year ORDER BY year""")), ""]

# ---- Study region -----------------------------------------------------------
out += ["## Study region: usable accidents per year (departments 75, 92, 93, 94)", "",
        table(["Year", "Accidents"],
              rows(f"""SELECT year, count(*) FROM crashes
                  WHERE exclusion_reason IS NULL AND dep IN {REGION_SQL}
                  GROUP BY year ORDER BY year""")), ""]

out += ["## Study region: usable accidents by department (2019-2025)", "", table(
    ["Dep", "Accidents"],
    rows(f"""SELECT dep, count(*) FROM crashes
        WHERE exclusion_reason IS NULL AND dep IN {REGION_SQL}
        GROUP BY dep ORDER BY dep""")), ""]

# ---- Time -------------------------------------------------------------------
out += ["## Timestamp ties (matters for the replay order)", "", table(
    ["Usable accidents", "Distinct timestamps", "Largest group sharing a timestamp"],
    rows("""SELECT sum(n), count(*), max(n) FROM (
        SELECT count(*) AS n FROM crashes WHERE exclusion_reason IS NULL
        GROUP BY occurred_at) t""")), ""]

out += ["## Time precision (minutes)", "",
        "Uniform minutes would give 1.7% / 20% / 6.7%.", "", table(
    ["% at minute :00", "% at multiples of 5", "% at multiples of 15"],
    rows("""SELECT
        round(100.0*count(*) FILTER (WHERE extract(minute FROM occurred_at)::int = 0)/count(*),1),
        round(100.0*count(*) FILTER (WHERE extract(minute FROM occurred_at)::int % 5 = 0)/count(*),1),
        round(100.0*count(*) FILTER (WHERE extract(minute FROM occurred_at)::int % 15 = 0)/count(*),1)
        FROM crashes WHERE exclusion_reason IS NULL""")), ""]

# ---- Pipeline output (table `crash_events`) -----------------------------------
has_events = rows("SELECT to_regclass('public.crash_events')")[0][0] is not None
if has_events:
    source_n = rows(f"""SELECT count(*) FROM crashes
        WHERE exclusion_reason IS NULL AND dep IN {REGION_SQL}""")[0][0]
    events_n = rows("SELECT count(*) FROM crash_events")[0][0]
    out += ["## Pipeline output: reconciliation", "", table(
        ["Source accidents (study region)", "Rows in crash_events", "Match"],
        [(source_n, events_n, "OK" if source_n == events_n else "MISMATCH")]),
        "", "Full consistency checks: `scripts/check_pipeline.py`.", ""]

    out += ["## Pipeline output: snapping to the road network", "", table(
        ["Snap status", "Accidents", "Share (%)"],
        rows("""SELECT snap_status, count(*),
            round(100.0*count(*)/sum(count(*)) OVER (), 1)
            FROM crash_events GROUP BY 1 ORDER BY 2 DESC""")), ""]

    out += ["### Distance to the nearest road: how many accidents are farther than a threshold",
            "", table(
        ["Threshold (m)", "Accidents farther", "Share (%)"],
        rows("""SELECT t.m, count(*) FILTER (WHERE e.snap_distance_m > t.m),
            round(100.0*count(*) FILTER (WHERE e.snap_distance_m > t.m)/count(*), 2)
            FROM (VALUES (10),(25),(50),(75),(100),(200),(300)) AS t(m)
            CROSS JOIN crash_events e GROUP BY t.m ORDER BY t.m""")), ""]

    out += ["### Accidents farther than the snapping threshold", "", table(
        ["Accidents", "Distinct addresses", "Median distance (m)"],
        rows("""SELECT count(*), count(DISTINCT c.adr),
            round((percentile_cont(0.5) WITHIN GROUP (ORDER BY e.snap_distance_m))::numeric)
            FROM crash_events e JOIN crashes c USING (accident_id)
            WHERE e.snap_status = 'far'""")), "",
        "Most frequent addresses:", "", table(
        ["Address", "Accidents"],
        rows("""SELECT coalesce(c.adr, '(no address)'), count(*)
            FROM crash_events e JOIN crashes c USING (accident_id)
            WHERE e.snap_status = 'far' GROUP BY 1 ORDER BY 2 DESC, 1 LIMIT 10""")), ""]

    out += ["## Pipeline output: crashes per H3 cell (resolution 9)", "", table(
        ["Crashes in the cell", "Cells", "Crashes"],
        rows("""WITH c AS (SELECT h3_cell, count(*) AS n FROM crash_events GROUP BY 1)
            SELECT CASE WHEN n = 1 THEN '1' WHEN n <= 3 THEN '2-3'
                        WHEN n <= 10 THEN '4-10' WHEN n <= 30 THEN '11-30'
                        ELSE '31+' END AS bucket,
                   count(*), sum(n)
            FROM c GROUP BY 1 ORDER BY min(n)""")), ""]
else:
    out += ["## Pipeline output", "",
            "Table `crash_events` does not exist yet: run the consumer first.", ""]

# ---- Limits -----------------------------------------------------------------
out += ["## Limits of these checks", "",
        "- Coordinate checks confirm format and plausibility, not that a point is on the right road.",
        "- A short distance to the nearest road does not prove the crash belongs to that road; the 50 m threshold is a design choice.",
        "- The cause of accidents far from any drivable road is not established.",
        "- Code meanings (`grav`, `lum`, `atm`, ...) are not yet verified against each year's official description.",
        "- No exposure data (traffic volume): counts are not risk per vehicle-km.",
        "- Times are rounded (recorded mostly at multiples of 5 minutes), so order within a quarter hour is not meaningful.",
        ""]

with open("docs/quality-report.md", "w", encoding="utf-8") as f:
    f.write("\n".join(out))
print("wrote docs/quality-report.md")
